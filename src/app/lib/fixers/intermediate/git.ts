/** Fix GitHub Actions detached HEAD for PR builds by checking out with head_ref. */
export function fixGitHubActionsDetachedHead(logs: string, files: Array<{ path: string; content: string }>): RuleFix[] {
  if (!/detached HEAD|HEAD is now at|not a branch|cannot.*detached/i.test(logs)) return [];
  const fixes: RuleFix[] = [];
  for (const f of files) {
    if (!isGitHubWorkflow(f.path)) continue;
    if (f.content.includes('ref:') || f.content.includes('head_ref')) continue;
    const lines = f.content.split('\n');
    const out: string[] = [];
    let modified = false;
    for (let i = 0; i < lines.length; i++) {
      out.push(lines[i]);
      if (/uses:\s*actions\/checkout/.test(lines[i])) {
        const hasWithNext = i + 1 < lines.length && lines[i + 1].trim() === 'with:';
        if (hasWithNext) {
          out.push(lines[++i]);
          out.push(`          ref: \${{ github.head_ref || github.ref_name }}`);
        } else {
          out.push('        with:');
          out.push(`          ref: \${{ github.head_ref || github.ref_name }}`);
        }
        modified = true;
      }
    }
    if (modified)
      fixes.push({ path: f.path, content: out.join('\n'), explanation: 'Added ref: github.head_ref to checkout — GitHub Actions checks out a merge commit SHA for PRs, resulting in detached HEAD; using github.head_ref attaches to the actual PR branch so git commands like git tag, git commit, and branch-aware tools work correctly', confidence: 95 });
  }
  return fixes;
}

