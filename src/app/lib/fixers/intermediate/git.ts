/** Add fetch-depth: 0 to checkout when shallow clone blocks git describe / tag operations. */
export function fixShallowClone(logs: string, files: Array<{ path: string; content: string }>): RuleFix[] {
  if (!/shallow.*update not allowed|fatal.*shallow|git describe.*fatal|tags.*not.*found/i.test(logs)) return [];
  const fixes: RuleFix[] = [];
  for (const f of files) {
    if (!isGitHubWorkflow(f.path) || f.content.includes('fetch-depth:')) continue;
    const lines = f.content.split('\n');
    const out: string[] = [];
    let modified = false;
    for (let i = 0; i < lines.length; i++) {
      out.push(lines[i]);
      if (/uses:\s*actions\/checkout/.test(lines[i])) {
        if (i + 1 < lines.length && lines[i + 1].trim() === 'with:') {
          out.push(lines[++i]);
          out.push('          fetch-depth: 0');
          out.push('          fetch-tags: true');
        } else {
          out.push('        with:');
          out.push('          fetch-depth: 0');
          out.push('          fetch-tags: true');
        }
        modified = true;
      }
    }
    if (modified)
      fixes.push({ path: f.path, content: out.join('\n'), explanation: 'Added fetch-depth: 0 + fetch-tags: true — shallow clone missing full git history/tags; semantic versioning tools require full history to determine the previous version', confidence: 100 });
  }
  return fixes;
}

/** Fix invalid branch reference — switch to HEAD/main when branch doesn't exist. */
export function fixInvalidBranchReference(logs: string, files: Array<{ path: string; content: string }>): RuleFix[] {
  if (!/invalid reference|branch.*not found|unknown revision|pathspec.*did not match|no upstream configured/i.test(logs)) return [];
  const branchMatch = logs.match(/(?:branch|ref|pathspec)\s+['"`]?([a-zA-Z0-9/_.-]+)['"`]?\s+(?:not found|did not match|unknown)/i);
  const badBranch = branchMatch?.[1] ?? '';
  const fixes: RuleFix[] = [];
  for (const f of files) {
    if (!isGitHubWorkflow(f.path) && !isGitLabCI(f.path)) continue;
    if (badBranch && !f.content.includes(badBranch)) continue;
    let content = f.content;
    if (badBranch) {
      content = content.replace(new RegExp(`\\b${badBranch.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'g'), 'main');
    }
    content = content.replace(
      /git checkout\s+[\w/-]+(?!\s*\$\{\{)/g,
      "git checkout \${{ github.ref_name || 'main' }}",
    );
    if (content !== f.content)
      fixes.push({ path: f.path, content, explanation: `Replaced hardcoded branch "${badBranch || 'unknown'}" with dynamic ref — the branch was deleted, renamed, or never created`, confidence: 100 });
  }
  return fixes;
}

/** Migrate hardcoded "master" branch references to "main". */
export function fixDefaultBranchRename(logs: string, files: Array<{ path: string; content: string }>): RuleFix[] {
  if (!/branch.*master.*not found|unknown revision.*master|src refspec master/i.test(logs)) return [];
  const fixes: RuleFix[] = [];
  for (const f of files) {
    if (!isGitHubWorkflow(f.path) && !isGitLabCI(f.path)) continue;
    if (!f.content.includes('master')) continue;
    const fixed = f.content
      .replace(/\bon:\s*\n(\s+)push:\s*\n(\s+)branches:\s*\n(\s+)- master\b/g,
        'on:\n$1push:\n$2branches:\n$3- main')
      .replace(/git (push|checkout|merge|rebase)\s+origin\s+master\b/g, 'git $1 origin main')
      .replace(/(?<!\w)master(?!\w)/g, (m, offset, str) => {
        // Don't replace in comments about "master key" etc, or in quoted template strings that reference secrets
        const context = str.slice(Math.max(0, offset - 20), offset + m.length + 20);
        if (/secret|key|password|token|#/i.test(context)) return m;
        return 'main';
      });
    if (fixed !== f.content)
      fixes.push({ path: f.path, content: fixed, explanation: 'Renamed "master" → "main" — the default branch was renamed; hardcoded "master" references cause "branch not found" errors in checkout, push, and branch triggers', confidence: 90 });
  }
  return fixes;
}

