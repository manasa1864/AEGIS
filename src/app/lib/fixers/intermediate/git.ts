/** Switch git pull to use rebase strategy to avoid merge commit noise in CI. */
export function fixGitRebasePullStrategy(logs: string, files: Array<{ path: string; content: string }>): RuleFix[] {
  if (!/hint:.*divergent branches|need to specify how to reconcile|pull.*not possible.*fast-forward/i.test(logs)) return [];
  const fixes: RuleFix[] = [];
  for (const f of files) {
    if (!isGitHubWorkflow(f.path) && !isGitLabCI(f.path)) continue;
    if (!f.content.includes('git pull')) continue;
    let content = f.content;
    // Set pull.rebase globally before any pull
    if (!content.includes('pull.rebase')) {
      content = content.replace(
        /(run:\s*\|?\s*\n(?:\s+[^\n]+\n)*\s+git pull)/m,
        (m) => `run: |\n          git config pull.rebase true\n          ${m.replace(/^\s*run:\s*\|?\s*\n\s+/, '')}`,
      );
    }
    // Patch bare git pull calls
    content = content.replace(/git pull\b(?!\s+--rebase|\s+origin\s+\S+\s+--rebase)/g, 'git pull --rebase');
    if (content !== f.content)
      fixes.push({ path: f.path, content, explanation: 'Added pull.rebase=true and --rebase flag — git pull in CI fails when local and remote have diverged; rebase replays local commits on top of fetched commits, avoiding a spurious merge commit', confidence: 90 });
  }
  return fixes;
}

/** Add .gitattributes merge=ours driver for lock files to prevent binary merge conflicts. */
export function fixBinaryMergeDriver(logs: string, files: Array<{ path: string; content: string }>): RuleFix[] {
  if (!/conflict.*lock|merge.*Gemfile\.lock|merge.*package-lock|merge.*yarn\.lock|merge.*pnpm-lock/i.test(logs)) return [];
  const hasAttrs = files.some(f => f.path.endsWith('.gitattributes'));
  if (hasAttrs) return [];
  // Inject a .gitattributes file that marks lock files as binary (merge=ours)
  const lockAttrContent = [
    '# Auto-generated by Aegis: prevent merge conflicts in lock files',
    'package-lock.json merge=ours',
    'yarn.lock merge=ours',
    'pnpm-lock.yaml merge=ours',
    'Gemfile.lock merge=ours',
    'poetry.lock merge=ours',
    'Pipfile.lock merge=ours',
    'composer.lock merge=ours',
    'Cargo.lock merge=ours',
    '*.lock merge=ours',
  ].join('\n');
  // Find a workflow to add the git merge driver setup step
  const fixes: RuleFix[] = [];
  fixes.push({ path: '.gitattributes', content: lockAttrContent, explanation: 'Created .gitattributes with merge=ours for lock files — lock file merge conflicts are always wrong; the correct resolution is to regenerate the lock file after merge, not to manually merge line-by-line', confidence: 85 });
  for (const f of files) {
    if (!isGitHubWorkflow(f.path)) continue;
    if (f.content.includes('merge.ours')) continue;
    const patched = insertStepBefore(
      f.content,
      /uses:\s*actions\/checkout/,
      `      - name: Configure lock-file merge driver\n        run: git config --global merge.ours.driver true`,
    );
    if (patched)
      fixes.push({ path: f.path, content: patched, explanation: 'Registered the "ours" merge driver globally — .gitattributes references it but it must be registered in git config; without registration git ignores the merge= attribute', confidence: 90 });
  }
  return fixes;
}

