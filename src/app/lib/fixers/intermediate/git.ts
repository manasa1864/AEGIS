/** Resolve merge conflict markers by keeping the "ours" (HEAD/left) section. */
export function fixMergeConflictMarkers(files: Array<{ path: string; content: string }>): RuleFix[] {
  const fixes: RuleFix[] = [];
  for (const f of files) {
    if (!/<<<<<<< /.test(f.content)) continue;
    const fixed = f.content.replace(
      /^<<<<<<< [^\n]+\n([\s\S]*?)^=======\n[\s\S]*?^>>>>>>> [^\n]+\n?/gm,
      '$1',
    );
    if (fixed !== f.content)
      fixes.push({ path: f.path, content: fixed, explanation: `Resolved merge conflict markers in ${f.path} — kept "ours" (HEAD) section; REVIEW THIS CHANGE — automatic resolution may discard the other branch's changes`, confidence: 100 });
  }
  return fixes;
}

